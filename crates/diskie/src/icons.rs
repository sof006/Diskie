impl AssetSource for Icons {
    fn load(&self, path: &str) -> Result<Option<Cow<'static, [u8]>>> {
        let name = path.trim_start_matches("icons/").trim_end_matches(".svg");
        Ok(body(name).map(|b| Cow::Owned(format!("{HEAD}{b}</svg>").into_bytes())))
    }

    fn list(&self, _path: &str) -> Result<Vec<SharedString>> {
        Ok(Vec::new())
    }
}

/// `icon("trash")` → the asset path GPUI's `svg()` element wants.
pub fn path(name: &'static str) -> SharedString {
    SharedString::from(format!("icons/{name}.svg"))
}
